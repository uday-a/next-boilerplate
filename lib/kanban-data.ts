// Due dates are offsets from today so the board always shows a mix of
// overdue / due-soon / later tasks, whenever the demo is opened.
function daysFromToday(days: number): string {
  const d = new Date()
  d.setDate(d.getDate() + days)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

function comment(id: string, who: AssigneeKey, text: string, time: string): CommentItem {
  return { id, author: assignees[who].name, authorColor: assignees[who].color, text, time }
}

